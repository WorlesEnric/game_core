        private static AudioSetDefinition AuthorAudio(UiAudioAuthoringReport report)
        {
            List<ProceduralClipSpec> specs = AudioSpecs();
            ProceduralAudioGenerator.Generate(GeneratedFolder, AudioManifestName, specs);
            AssetDatabase.Refresh(ImportAssetOptions.ForceSynchronousImport);
            AudioMixer? mixer = AssetDatabase.LoadAssetAtPath<AudioMixer>(MixerPath);
            AudioBankDefinition bank = LoadOrCreate<AudioBankDefinition>(BankPath, b => b.EnsureAuthoringId());
            bank.SetMixer(mixer);
            for (int i = 0; i < specs.Count; i++)
            {
                ProceduralClipSpec spec = specs[i];
                AudioClip? clip = AssetDatabase.LoadAssetAtPath<AudioClip>(GeneratedFolder + "/" + spec.file);
                if (clip == null)
                {
                    report.Diagnostics.Add(new GameplayDiagnostic(PresentationDiagnosticCodes.AudioMissingClip, spec.id, spec.file + " did not import"));
                    continue;
                }

                AudioGroup group = spec.id.StartsWith("ambience.", StringComparison.Ordinal) ? AudioGroup.Ambience
                    : spec.id.StartsWith("music.", StringComparison.Ordinal) || spec.id.StartsWith("stinger.", StringComparison.Ordinal) ? AudioGroup.Music
                    : spec.id.StartsWith("sfx.ui.", StringComparison.Ordinal) ? AudioGroup.Ui : AudioGroup.Sfx;
                bool spatial = group == AudioGroup.Sfx;
                AudioTools.AssignClip(bank, spec.id, clip, group, spatial ? 0.9f : 1f, spec.loop, spatial);
                report.Clips++;
            }

            EditorUtility.SetDirty(bank);
            AudioSetDefinition set = LoadOrCreate<AudioSetDefinition>(AudioSetPath, s => s.EnsureAuthoringId());
            if (set.Bank != bank)
            {
                set.Configure(bank, set.MusicStates, set.StartMusicState, set.Ambiences);
            }

            AudioTools.SetMusicState(set, MusicExplore, MusicExplore, 2500, string.Empty, true, AudioRoot + "/Definitions/MusicState_Explore.asset");
            AudioTools.SetMusicState(set, MusicTense, MusicTense, 1200, Bell, false, AudioRoot + "/Definitions/MusicState_Tense.asset");
            AudioTools.SetMusicState(set, MusicEnding, MusicEnding, 4000, Bell, false, AudioRoot + "/Definitions/MusicState_Ending.asset");
            Ambience(set, "ThornwickVillage", "ambience.village");
            Ambience(set, "BlackmereMarsh", "ambience.marsh");
            Ambience(set, "DrownedBelfry", "ambience.belfry");
            EditorUtility.SetDirty(set);
            return set;
        }

        private static void Ambience(AudioSetDefinition set, string regionAsset, string clipId)
        {
            RegionDefinition? region = AssetDatabase.LoadAssetAtPath<RegionDefinition>(RegionsFolder + "/" + regionAsset + ".asset");
            if (region == null)
            {
                throw new InvalidOperationException("region " + regionAsset + " is missing; author the P1.1 world first");
            }

            AudioTools.SetAmbience(set, region, clipId, 0.8f, 2500, AudioRoot + "/Definitions/Ambience_" + regionAsset + ".asset");
        }


        /// <summary>Creates whatever is missing and refreshes the rest; returns the report with validator diagnostics.</summary>
        public static UiAudioAuthoringReport Author()
        {
            var report = new UiAudioAuthoringReport();
            EnsureFolder(AudioRoot + "/Definitions");
            EnsureFolder(GeneratedFolder);
            EnsureFolder(UiRoot + "/Definitions");
            EnsureFolder(UiRoot + "/Resources/Hollowmere");
            AudioSetDefinition set = AuthorAudio(report);
            ScreenFlowDefinition flow = AuthorUi(report);
            HollowmereUiAudioContent content = LoadOrCreate<HollowmereUiAudioContent>(ContentPath, null);
            content.Configure(flow, set);
            EditorUtility.SetDirty(content);
            AssetDatabase.SaveAssets();
            report.Diagnostics.AddRange(AudioValidator.Validate(set));
            report.Diagnostics.AddRange(UiValidator.Validate(flow));
            return report;
        }


// Hollowmere - authors the P1.5 UI and audio content through the ui.* and audio.* tools (idempotent).
//
//   Assets/Hollowmere/Audio/Generated/*.wav + HollowmereAudio.manifest.json   procedural placeholder audio
//   Assets/Hollowmere/Audio/Definitions/*.asset                                bank, music states, ambiences, audio set
//   Assets/Hollowmere/Audio/HollowmereMixer.mixer                              hand-written mixer (Master + 4 groups)
//   Assets/Hollowmere/UI/Theme/*                                               USS, TSS, PanelSettings, ThemeDefinition
//   Assets/Hollowmere/UI/Screens/*.uxml + Assets/Hollowmere/UI/Definitions/*   documents with their binding maps, flow
//   Assets/Hollowmere/UI/Resources/Hollowmere/UiAudio.asset                    the content asset GameBoot loads
// Existing assets keep their GUIDs and authoring ids; bindings are re-applied (no-ops when unchanged) and the audio is
// regenerated byte-identically. No world definition is touched, so the world bake is unaffected.

        private static ScreenFlowDefinition AuthorUi(UiAudioAuthoringReport report)
        {
            AssetDatabase.ImportAsset(UssPath, ImportAssetOptions.ForceSynchronousImport);
            AssetDatabase.ImportAsset(TssPath, ImportAssetOptions.ForceSynchronousImport);
            StyleSheet? uss = AssetDatabase.LoadAssetAtPath<StyleSheet>(UssPath);
            ThemeStyleSheet? tss = AssetDatabase.LoadAssetAtPath<ThemeStyleSheet>(TssPath);
            PanelSettings panel = LoadOrCreate<PanelSettings>(PanelSettingsPath, p =>
            {
                p.scaleMode = PanelScaleMode.ScaleWithScreenSize;
                p.referenceResolution = new Vector2Int(1920, 1080);
                p.screenMatchMode = PanelScreenMatchMode.MatchWidthOrHeight;
                p.match = 0.5f;
            });
            if (tss != null && panel.themeStyleSheet != tss)
            {
                panel.themeStyleSheet = tss;
                EditorUtility.SetDirty(panel);
            }

            ThemeDefinition theme = LoadOrCreate<ThemeDefinition>(ThemePath, t => t.EnsureAuthoringId());
            ScreenFlowDefinition flow = LoadOrCreate<ScreenFlowDefinition>(FlowPath, f =>
            {
                f.EnsureAuthoringId();
                f.Configure("Hollowmere", UiScreen.Menu, null, 3000);
            });
            UiTools.SetTheme(flow, theme, panel, tss, uss != null ? new[] { uss } : Array.Empty<StyleSheet>());
            flow.SetMessages(Messages());
            EditorUtility.SetDirty(flow);

            var plans = new[]
            {
                new ScreenPlan(UiScreen.Hud, "Hud.uxml", "Doc_Hud.asset", 0),
                new ScreenPlan(UiScreen.Hud, "Dialogue.uxml", "Doc_Dialogue.asset", 20),
                new ScreenPlan(UiScreen.Menu, "MainMenu.uxml", "Doc_MainMenu.asset", 10),
                new ScreenPlan(UiScreen.Pause, "Pause.uxml", "Doc_Pause.asset", 10),
                new ScreenPlan(UiScreen.Settings, "Settings.uxml", "Doc_Settings.asset", 10),
                new ScreenPlan(UiScreen.Save, "SaveLoad.uxml", "Doc_Save.asset", 10),
                new ScreenPlan(UiScreen.Load, "SaveLoad.uxml", "Doc_Load.asset", 10),
                new ScreenPlan(UiScreen.Journal, "Journal.uxml", "Doc_Journal.asset", 10),
                new ScreenPlan(UiScreen.Inventory, "Inventory.uxml", "Doc_Inventory.asset", 10),
                new ScreenPlan(UiScreen.Ending, "Ending.uxml", "Doc_Ending.asset", 10),
            };
            for (int i = 0; i < plans.Length; i++)
            {
                UiDocumentDefinition document = Document(flow, plans[i]);
                report.Bindings += BindScreen(document, plans[i].Screen, plans[i].Uxml);
                report.Documents++;
            }

            return flow;
        }

        private static UiDocumentDefinition Document(ScreenFlowDefinition flow, ScreenPlan plan)
        {
            AssetDatabase.ImportAsset(plan.Uxml, ImportAssetOptions.ForceSynchronousImport);
            UiDocumentDefinition? document = AssetDatabase.LoadAssetAtPath<UiDocumentDefinition>(plan.Asset);
            if (document == null)
            {
                return UiTools.AddScreen(flow, plan.Screen, plan.Uxml, plan.Layer, plan.Asset);
            }

            document.EnsureAuthoringId();
            document.Configure(plan.Screen, plan.Layer, AssetDatabase.LoadAssetAtPath<VisualTreeAsset>(plan.Uxml));
            EditorUtility.SetDirty(document);
            if (flow.AddDocument(document))
            {
                EditorUtility.SetDirty(flow);
            }

            return document;
        }


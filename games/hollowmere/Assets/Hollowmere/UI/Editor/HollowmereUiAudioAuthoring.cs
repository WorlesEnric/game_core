        private static int B(UiDocumentDefinition d, string element, string source, string property = "text", string format = "")
        {
            UiTools.Bind(d, element, source, property, format);
            return 1;
        }

        private static int C(UiDocumentDefinition d, string element, string command, string property = "clicked")
        {
            UiTools.SetCommand(d, element, command, property);
            return 1;
        }

        private static List<UiMessageEntry> Messages()
        {
            var messages = new List<UiMessageEntry>
            {
                new UiMessageEntry(UiMessageIds.Saved, "Game saved."),
                new UiMessageEntry(UiMessageIds.Loaded, "Game loaded."),
                new UiMessageEntry(UiMessageIds.Deleted, "Save deleted."),
                new UiMessageEntry(UiMessageIds.NoSave, "There is no saved game yet."),
                new UiMessageEntry(UiMessageIds.SaveUnavailable, "Saving is not available in this build (" + PresentationDiagnosticCodes.UiSaveUnavailable + ")."),
            };
            foreach (SaveRefusalCode code in (SaveRefusalCode[])Enum.GetValues(typeof(SaveRefusalCode)))
            {
                string id = SaveRefusal.IdOf(code);
                if (code != SaveRefusalCode.None && messages.FindIndex(m => m.Id == id) < 0)
                {
                    messages.Add(new UiMessageEntry(id, id + ": " + SaveRefusal.DefaultHint(code)));
                }
            }

            return messages;
        }


    /// <summary>What one authoring pass did.</summary>
    public sealed class UiAudioAuthoringReport
    {
        public int Clips { get; internal set; }

        public int Documents { get; internal set; }

        public int Bindings { get; internal set; }

        public List<GameplayDiagnostic> Diagnostics { get; } = new List<GameplayDiagnostic>();

        public bool Ok => Diagnostics.Count == 0;

        public override string ToString()
        {
            string text = Clips + " clips, " + Documents + " documents, " + Bindings + " bindings, " + Diagnostics.Count + " diagnostics";
            for (int i = 0; i < Diagnostics.Count; i++)
            {
                text += "\n  " + Diagnostics[i].Code + " " + Diagnostics[i].SubjectId + ": " + Diagnostics[i].Message;
            }

            return text;
        }
    }

